class Signature(BaseModel):
    """
    DSPy-style Signature definition for prompts.
    Defines the contract for input/output/constraints.
    """

    input_variables: List[str] = Field(
        default_factory=list,
        description="List of expected input variable names (e.g. ['question', 'context'])",
    )
    output_format: str = Field(
        default="text",
        description="Expected output format (e.g. 'json', 'text', 'markdown')",
    )
    constraints: List[str] = Field(
        default_factory=list,
        description="List of constraints (e.g. 'No verbose explanations', 'JSON only')",
    )


class PromptMetadata(BaseModel):
    """
    Schema for validating the JSON 'metadata' field in the database.
    Ensures safe persistence of nested fields.
    """

    model_specifics: Dict[str, Any] = Field(default_factory=dict)
    variables: List[str] = Field(default_factory=list)
    guidelines: str = ""
    timestamp: str = ""
    signature: Optional[Signature] = Field(default_factory=Signature)

    @field_validator("signature", mode="before")
    @classmethod
    def validate_signature(cls, v):
        if v is None:
            return Signature()
        if isinstance(v, dict):
            return Signature(**v)
        return v


